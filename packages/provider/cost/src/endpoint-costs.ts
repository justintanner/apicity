// ─── Helper functions ───

export function getEndpointCost(key: string): EndpointCostInfo | undefined {
  return ENDPOINT_COSTS[key];
}

export function getTier(key: string): CostTier | undefined {
  return ENDPOINT_COSTS[key]?.tier;
}

export function isExpensiveOrWorse(key: string): boolean {
  const tier = getTier(key);
  return tier === "expensive" || tier === "prohibitive";
}

export function isProhibitive(key: string): boolean {
  return getTier(key) === "prohibitive";
}

export function listByTier(tier: CostTier): EndpointCostInfo[] {
  return Object.values(ENDPOINT_COSTS).filter((e) => e.tier === tier);
}

export function listByProvider(provider: string): EndpointCostInfo[] {
  return Object.values(ENDPOINT_COSTS).filter((e) => e.provider === provider);
}

export function countByTier(): Record<CostTier, number> {
  const counts: Record<CostTier, number> = {
    free: 0,
    cheap: 0,
    expensive: 0,
    prohibitive: 0,
  };
  for (const entry of Object.values(ENDPOINT_COSTS)) {
    counts[entry.tier]++;
  }
  return counts;
}
