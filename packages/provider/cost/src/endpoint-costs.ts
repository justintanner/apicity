// Static endpoint cost tier classification.
//
// Every endpoint exposed by the provider packages is mapped to a cost tier
// that the gate system can consult before dispatching a request.
//
// Tier definitions:
//   free      — no marginal cost per request (metadata, listings, status checks)
//   cheap     — very low cost (token counting, small file ops, health checks)
//   expensive — significant cost per request (LLM inference, image/video/audio
//               generation, speech-to-text, embeddings, translation)
//   prohibitive — very high cost per request (fine-tuning, batch training,
//                 large-scale batch inference)

export type CostTier = "free" | "cheap" | "expensive" | "prohibitive";

