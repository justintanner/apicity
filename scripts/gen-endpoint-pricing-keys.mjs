#!/usr/bin/env node
// Pure local generation: URL paths are the pricing keys for fixed fal and
// WaveSpeed routes. KIE's distinct Suno operations need reviewed fixed keys.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const root = new URL("../", import.meta.url);
const overrides = JSON.parse(
  readFileSync(
    new URL("lib/endpoint-pricing-overrides.json", import.meta.url),
    "utf8"
  )
);
const keys = {};
const used = new Set();
for (const row of readFileSync(
  new URL("scripts/endpoint-docs.tsv", root),
  "utf8"
)
  .trim()
  .split("\n")
  .slice(1)) {
  const [provider, dotPath, method, url] = row.split("\t");
  // Method-qualified overrides distinguish callable GET/POST siblings.
  const overridePath = Object.hasOwn(
    overrides[provider] ?? {},
    `${method} ${dotPath}`
  )
    ? `${method} ${dotPath}`
    : dotPath;
  let key = overrides[provider]?.[overridePath];
  if (key) used.add(`${provider} ${overridePath}`);
  if (
    (provider === "fal" || provider === "wavespeed") &&
    method === "POST" &&
    !url.includes("{")
  ) {
    const parsed = new URL(url);
    if (provider === "fal" && parsed.hostname === "fal.run")
      key = parsed.pathname.slice(1);
    if (
      provider === "wavespeed" &&
      parsed.pathname.startsWith("/api/v3/") &&
      dotPath !== "api.v3.model.price"
    ) {
      key = parsed.pathname.slice("/api/v3/".length);
    }
  }
  if (key) keys[`${provider} ${method} ${dotPath}`] = key;
}
for (const [provider, rows] of Object.entries(overrides)) {
  for (const dotPath of Object.keys(rows)) {
    if (!used.has(`${provider} ${dotPath}`))
      throw new Error(`Stale pricing override: ${provider} ${dotPath}`);
  }
}
const sorted = Object.fromEntries(
  Object.entries(keys).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
);
const next = await format(
  "// Generated by scripts/gen-endpoint-pricing-keys.mjs. Do not edit.\n" +
    "export const ENDPOINT_PRICING_KEYS: Readonly<Record<string, string>> = " +
    JSON.stringify(sorted) +
    ";\n",
  { parser: "typescript" }
);
const target = new URL(
  "packages/provider/cost/src/endpoint-pricing-keys.ts",
  root
);
let current = "";
try {
  current = readFileSync(target, "utf8");
} catch {
  /* missing is drift */
}
if (next !== current) {
  if (process.argv.includes("--check")) {
    console.error(
      "Endpoint pricing keys are stale; run pnpm run gen:endpoint-pricing-keys"
    );
    process.exitCode = 1;
  } else {
    writeFileSync(target, next);
    console.log(`wrote ${fileURLToPath(target)}`);
  }
}
