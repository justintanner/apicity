function isObject(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function readJson(filePath) {
  try {
    return JSON.parse(fs.readFileSync(filePath, "utf8"));
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    throw new Error(`could not read ${filePath}: ${message}`);
  }
}

function sameList(left, right) {
  return (
    Array.isArray(left) &&
    Array.isArray(right) &&
    left.length === right.length &&
    left.every((item, index) => item === right[index])
  );
}

function wrapProse(text, width = PROSE_WIDTH) {
  const tokens = text.match(/\[[^\]]+\]\([^)]+\)|\S+/g) ?? [];
  const lines = [];
  let line = "";
  for (const token of tokens) {
    // A link longer than the width is one token. The comma after it must stay
    // on that link, or the next line starts with ", captured".
    const punctuation = /^[,.;:!?]+$/.test(token);
    if (line.length === 0) {
      line = token;
      continue;
    }
    if (punctuation) {
      line += token;
      continue;
    }
    if (line.length + 1 + token.length > width) {
      lines.push(line);
      line = token;
    } else {
      line += ` ${token}`;
    }
  }
  if (line.length > 0) lines.push(line);
  return lines.join("\n");
}

export function textCarriesTypeKeyword(type, text) {
  const rule = TYPE_KEYWORDS[type];
  if (!rule || typeof text !== "string") return false;
  let haystack = text;
  for (const blocked of rule.exclude) {
    haystack = haystack.split(blocked).join("\0");
  }
  return rule.include.some((keyword) => haystack.includes(keyword));
}

export function loadCatalog(catalogPath = CATALOG_PATH) {
  return readJson(catalogPath);
}

export function loadEndpointDocRows(tsvPath = ENDPOINT_DOCS_PATH) {
  const lines = fs.readFileSync(tsvPath, "utf8").split("\n").filter(Boolean);
  const rows = [];
  for (let i = 1; i < lines.length; i++) {
    const [provider, dotPath, method, fullUrl, docsUrl] = lines[i].split("\t");
    rows.push({
      provider,
      dotPath,
      method,
      fullUrl,
      docsUrl: docsUrl ?? "",
    });
  }
  return rows;
}

/**
 * Concatenate a provider's TypeScript sources. The URL comment above each
 * factory leaf is the live endpoint record the comment lint already requires.
 */
export function providerSourceText(provider, repoRoot = REPO_ROOT) {
  const dir = path.join(repoRoot, "packages", "provider", provider, "src");
  const parts = [];
  const walk = (current) => {
    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      const child = path.join(current, entry.name);
      if (entry.isDirectory()) {
        walk(child);
      } else if (entry.name.endsWith(".ts")) {
        parts.push(fs.readFileSync(child, "utf8"));
      }
    }
  };
  walk(dir);
  return parts.join("\n");
}

/**
 * True when `url` occurs in `source` and is not only a prefix of a longer
 * path (`…/videos` must not match `…/videos/upscale`).
 */
export function sourceHasExactUrl(source, url) {
  const escaped = url.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return new RegExp(`${escaped}(?![A-Za-z0-9_./-])`).test(source);
}

export function catalogProblems(catalog) {
  const problems = [];
  if (!Array.isArray(catalog)) return ["catalog must be an array"];
  if (catalog.length !== TYPE_IDENTITY.length) {
    problems.push(
      `catalog must list ${TYPE_IDENTITY.length} types in FRONTIER_TYPES order`
    );
  }
  TYPE_IDENTITY.forEach((identity, index) => {
    const item = catalog[index];
    const where = `catalog[${index}]`;
    if (!isObject(item)) {
      problems.push(`${where} must be an object`);
      return;
    }
    if (item.type !== identity.type) {
      problems.push(`${where}.type must be ${identity.type}`);
    }
    if (item.name !== identity.name) {
      problems.push(`${where}.name must be ${identity.name}`);
    }
    if (item.derived !== identity.derived) {
      problems.push(`${where}.derived must be ${String(identity.derived)}`);
    }
    if (!sameList(item.aliases, identity.aliases)) {
      problems.push(
        `${where}.aliases must be ${JSON.stringify(identity.aliases)}`
      );
    }
    if (typeof item.leaderboardId !== "string") {
      problems.push(`${where}.leaderboardId must be a string`);
    } else if (!identity.derived && item.leaderboardId.trim() === "") {
      problems.push(`${where}.leaderboardId must be a non-empty string`);
    }
    if (typeof item.sourceUrl !== "string") {
      problems.push(`${where}.sourceUrl must be a string`);
    } else if (identity.derived) {
      if (item.sourceUrl !== "" && !item.sourceUrl.startsWith("https://")) {
        problems.push(`${where}.sourceUrl must be empty or an https URL`);
      }
    } else if (!item.sourceUrl.startsWith("https://")) {
      problems.push(`${where}.sourceUrl must be an https URL`);
    }
  });
  return problems;
}

/**
 * Shape checks for one leaderboard.json.
 *
 * A derived snapshot (`derived: true`) names the leaderboards it re-ranks in
 * `sources` instead of a `leaderboardId`. `derivedProblems` checks its
 * entries against those boards.
 */
export function snapshotProblems(snapshot) {
  const problems = [];
  if (!isObject(snapshot)) return ["snapshot must be an object"];
  if (snapshot.derived !== undefined && typeof snapshot.derived !== "boolean") {
    problems.push("snapshot.derived must be a boolean when present");
  }
  if (snapshot.derived === true) {
    if (snapshot.leaderboardId !== undefined) {
      problems.push(
        "a derived snapshot names its sources instead of a leaderboardId"
      );
    }
    if (
      !Array.isArray(snapshot.sources) ||
      snapshot.sources.length === 0 ||
      !snapshot.sources.every(
        (source) => typeof source === "string" && source.trim() !== ""
      )
    ) {
      problems.push("snapshot.sources must list the source leaderboard ids");
    } else if (new Set(snapshot.sources).size !== snapshot.sources.length) {
      problems.push("snapshot.sources lists a leaderboard twice");
    }
  } else {
    if (
      typeof snapshot.leaderboardId !== "string" ||
      snapshot.leaderboardId.trim() === ""
    ) {
      problems.push("snapshot.leaderboardId must be a non-empty string");
    }
    if (snapshot.sources !== undefined) {
      problems.push("snapshot.sources belongs to a derived snapshot");
    }
  }
  if (
    typeof snapshot.sourceUrl !== "string" ||
    !snapshot.sourceUrl.startsWith("https://")
  ) {
    problems.push("snapshot.sourceUrl must be an https URL");
  }
  if (
    typeof snapshot.capturedOn !== "string" ||
    !/^\d{4}-\d{2}-\d{2}$/.test(snapshot.capturedOn)
  ) {
    problems.push("snapshot.capturedOn must be YYYY-MM-DD");
  }
  if (
    typeof snapshot.methodology !== "string" ||
    snapshot.methodology.trim() === ""
  ) {
    problems.push("snapshot.methodology must be a non-empty string");
  }
  if (!Array.isArray(snapshot.entries) || snapshot.entries.length === 0) {
    problems.push("snapshot.entries must be a non-empty array");
    return problems;
  }
  if (snapshot.entries.length > MAX_RANKS) {
    problems.push(
      `snapshot.entries has ${snapshot.entries.length} rows; coverage is the top ${MAX_RANKS}`
    );
  }

  const seenRanks = new Set();
  const seenModels = new Set();
  snapshot.entries.forEach((entry, index) => {
    const where = `snapshot.entries[${index}]`;
    if (!isObject(entry)) {
      problems.push(`${where} must be an object`);
      return;
    }
    if (!Number.isInteger(entry.rank) || entry.rank < 1) {
      problems.push(`${where}.rank must be a positive integer`);
    } else if (seenRanks.has(entry.rank)) {
      problems.push(`${where}.rank ${entry.rank} is duplicated`);
    } else {
      seenRanks.add(entry.rank);
    }
    if (typeof entry.model !== "string" || entry.model.trim() === "") {
      problems.push(`${where}.model must be a non-empty string`);
    } else if (seenModels.has(entry.model)) {
      problems.push(
        `${where}.model ${JSON.stringify(entry.model)} is duplicated`
      );
    } else {
      seenModels.add(entry.model);
    }
    if (typeof entry.creator !== "string" || entry.creator.trim() === "") {
      problems.push(`${where}.creator must be a non-empty string`);
    }
    if (!Number.isInteger(entry.elo)) {
      problems.push(`${where}.elo must be an integer`);
    }
  });

  const count = snapshot.entries.length;
  for (let rank = 1; rank <= count; rank++) {
    if (!seenRanks.has(rank)) {
      problems.push(`snapshot ranks must be contiguous; missing ${rank}`);
    }
  }
  for (const rank of seenRanks) {
    if (rank > count) {
      problems.push(
        `snapshot ranks must be contiguous 1..${count}; found ${rank}`
      );
    }
  }
  return problems;
}

/**
 * A derived list re-ranks the models of its source snapshots.
 *
 * Each entry has to come from a source and carry the better of its source
 * Elos, with the creator that board gives it; when a model has the same Elo
 * on both boards, the earlier source in `sources` supplies it. Entries run
 * from the best Elo down, and equal Elos keep source order, then source
 * rank. Every entry needs an endpoint: the list holds only models apicity
 * serves for the type.
 *
 * @param {object} snapshot the derived leaderboard.json
 * @param {Record<string, unknown>} endpointMap its endpoints.json
 * @param {Array<{ leaderboardId: string, entries: object[] }>} sources the
 *   source snapshots, in `snapshot.sources` order
 */
export function derivedProblems(snapshot, endpointMap, sources) {
  const problems = [];
  if (!isObject(snapshot) || !Array.isArray(snapshot.entries)) return problems;
  const best = new Map();
  sources.forEach((source, sourceIndex) => {
    const entries = Array.isArray(source?.entries) ? source.entries : [];
    for (const entry of entries) {
      if (!isObject(entry) || typeof entry.model !== "string") continue;
      const current = best.get(entry.model);
      if (current === undefined || entry.elo > current.elo) {
        best.set(entry.model, {
          elo: entry.elo,
          creator: entry.creator,
          board: source.leaderboardId,
          sourceIndex,
          rank: entry.rank,
        });
      }
    }
  });

  const ranked = [];
  snapshot.entries.forEach((entry, index) => {
    if (!isObject(entry) || typeof entry.model !== "string") return;
    const where = `snapshot.entries[${index}] ${JSON.stringify(entry.model)}`;
    const origin = best.get(entry.model);
    if (origin === undefined) {
      problems.push(`${where} is in no source snapshot`);
      return;
    }
    if (entry.elo !== origin.elo) {
      problems.push(
        `${where} elo must be ${origin.elo}, its better source Elo (${origin.board})`
      );
    }
    if (entry.creator !== origin.creator) {
      problems.push(
        `${where} creator must be ${JSON.stringify(origin.creator)}, as ${origin.board} gives it`
      );
    }
    const list = isObject(endpointMap) ? endpointMap[entry.model] : undefined;
    if (!Array.isArray(list) || list.length === 0) {
      problems.push(`${where} has no endpoint; a derived entry needs one`);
    }
    ranked.push({ model: entry.model, ...origin });
  });

  const actual = ranked.map((item) => item.model);
  const expected = [...ranked]
    .sort(
      (a, b) =>
        b.elo - a.elo || a.sourceIndex - b.sourceIndex || a.rank - b.rank
    )
    .map((item) => item.model);
  if (!sameList(expected, actual)) {
    problems.push(
      `entries must run from the best Elo down: ${expected.map((model) => JSON.stringify(model)).join(", ")}`
    );
  }
  return problems;
}

function endpointRecordProblems(entry, where) {
  const problems = [];
  if (!isObject(entry)) {
    problems.push(`${where} must be an object`);
    return problems;
  }
  for (const key of Object.keys(entry)) {
    if (!ENDPOINT_FIELDS.has(key)) {
      problems.push(`${where} has unknown field ${key}`);
    }
  }
  if (typeof entry.provider !== "string" || entry.provider === "") {
    problems.push(`${where}.provider must be a non-empty string`);
  }
  if (typeof entry.dotPath !== "string" || entry.dotPath === "") {
    problems.push(`${where}.dotPath must be a non-empty string`);
  }
  if (
    entry.modelId !== undefined &&
    (typeof entry.modelId !== "string" || entry.modelId === "")
  ) {
    problems.push(`${where}.modelId must be a non-empty string when present`);
  }
  if (
    entry.pricingKey !== undefined &&
    (typeof entry.pricingKey !== "string" || entry.pricingKey === "")
  ) {
    problems.push(
      `${where}.pricingKey must be a non-empty string when present`
    );
  } else if (entry.modelId === undefined && entry.pricingKey === undefined) {
    problems.push(
      `${where} needs pricingKey (a PRICING key, a fal endpoint id, or "unpriced")`
    );
  }
  return problems;
}

export function endpointMapProblems(snapshot, endpointMap) {
  const problems = [];
  if (!isObject(endpointMap)) return ["endpoint map must be an object"];
  const models = Array.isArray(snapshot?.entries)
    ? snapshot.entries
        .filter((entry) => isObject(entry) && typeof entry.model === "string")
        .map((entry) => entry.model)
    : [];
  const expected = new Set(models);
  for (const model of expected) {
    if (!Object.prototype.hasOwnProperty.call(endpointMap, model)) {
      problems.push(
        `endpoint map is missing ${JSON.stringify(model)} (use [] when unmapped)`
      );
    }
  }
  for (const model of Object.keys(endpointMap)) {
    if (!expected.has(model)) {
      problems.push(
        `endpoint map has ${JSON.stringify(model)}, which is not in the snapshot`
      );
    }
    const list = endpointMap[model];
    if (!Array.isArray(list)) {
      problems.push(`endpoint map ${JSON.stringify(model)} must be an array`);
      continue;
    }
    const seen = new Set();
    list.forEach((entry, index) => {
      const where = `endpoint map ${JSON.stringify(model)}[${index}]`;
      problems.push(...endpointRecordProblems(entry, where));
      if (!isObject(entry)) return;
      const key = `${entry.provider}\t${entry.dotPath}\t${entry.modelId ?? ""}`;
      if (seen.has(key)) {
        problems.push(
          `${where} duplicates ${entry.provider} ${entry.dotPath} ${entry.modelId ?? ""}`
        );
      } else {
        seen.add(key);
      }
    });
  }
  return problems;
}

function findDocRow(docsRows, provider, dotPath) {
  return docsRows.filter(
    (row) =>
      row.provider === provider &&
      row.dotPath === dotPath &&
      row.method === "POST"
  );
}

/**
 * Every mapped endpoint must resolve.
 *
 * A dedicated leaf (no modelId) has to carry the type keyword in its dot
 * path or its URL, or `ctx.leafDocuments(type, entry)`, when given, has to
 * find the mode in the leaf's own request schema. A shared callable's
 * modelId has to be in `ctx.registryHas(type, entry)`.
 */
export function resolutionProblems(type, endpointMap, ctx) {
  const problems = [];
  if (!isObject(endpointMap)) return problems;
  const { docsRows, registryHas, sourceHasUrl, leafDocuments } = ctx ?? {};
  if (
    typeof registryHas !== "function" ||
    typeof sourceHasUrl !== "function" ||
    !Array.isArray(docsRows)
  ) {
    return [
      "resolution context is missing docsRows, registryHas, or sourceHasUrl",
    ];
  }

  for (const [model, list] of Object.entries(endpointMap)) {
    if (!Array.isArray(list)) continue;
    list.forEach((entry, index) => {
      if (!isObject(entry) || typeof entry.provider !== "string") return;
      if (typeof entry.dotPath !== "string" || entry.dotPath === "") return;
      const where =
        `${JSON.stringify(model)}[${index}] ${entry.provider} ` +
        `${entry.dotPath}`;
      const rows = findDocRow(docsRows, entry.provider, entry.dotPath);
      if (rows.length !== 1) {
        problems.push(
          `${where} expected one POST endpoint-docs row for ${entry.dotPath}, found ${rows.length}`
        );
        return;
      }
      const fullUrl = rows[0].fullUrl ?? "";
      if (!sourceHasUrl(entry.provider, fullUrl)) {
        problems.push(
          `${where} URL ${fullUrl} is not in packages/provider/${entry.provider}/src`
        );
      }
      if (entry.modelId === undefined) {
        const named =
          textCarriesTypeKeyword(type, entry.dotPath) ||
          textCarriesTypeKeyword(type, fullUrl);
        const documented =
          typeof leafDocuments === "function" && leafDocuments(type, entry);
        if (!named && !documented) {
          problems.push(`${where} is not a ${type} endpoint`);
        }
        return;
      }
      if (!registryHas(type, entry)) {
        problems.push(
          `${where} model ${entry.modelId} is not in the ${entry.provider} ${type} model registry`
        );
      }
    });
  }
  return problems;
}

function typeDirectories(repoRoot) {
  return fs
    .readdirSync(path.join(repoRoot, "scripts", "frontier"), {
      withFileTypes: true,
    })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}

function knownType(type) {
  return TYPE_IDENTITY.some((identity) => identity.type === type);
}

/**
 * Catalog shape plus every present type directory.
 *
 * A missing directory is an empty registry entry, not an error. A present
 * directory must have both JSON files and a valid top-10 snapshot. A derived
 * type's snapshot must also match the source snapshots it names.
 */
export function structuralProblems(repoRoot = REPO_ROOT) {
  const problems = [];
  let catalog;
  try {
    catalog = loadCatalog(
      path.join(repoRoot, "scripts", "frontier", "catalog.json")
    );
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    return [message];
  }
  problems.push(...catalogProblems(catalog).map((problem) => problem));

  const codes = new Set(TYPE_IDENTITY.map((identity) => identity.type));
  for (const name of typeDirectories(repoRoot)) {
    if (!codes.has(name)) {
      problems.push(`scripts/frontier/${name} is not a frontier type`);
    }
  }

  if (!Array.isArray(catalog)) return problems;
  for (const identity of TYPE_IDENTITY) {
    const dir = path.join(repoRoot, "scripts", "frontier", identity.type);
    if (!fs.existsSync(dir)) continue;
    const leaderboardPath = path.join(dir, "leaderboard.json");
    const endpointPath = path.join(dir, "endpoints.json");
    if (!fs.existsSync(leaderboardPath) || !fs.existsSync(endpointPath)) {
      problems.push(
        `scripts/frontier/${identity.type} needs leaderboard.json and endpoints.json`
      );
      continue;
    }
    const snapshot = readJson(leaderboardPath);
    const endpointMap = readJson(endpointPath);
    const prefix = identity.type;
    for (const problem of snapshotProblems(snapshot)) {
      problems.push(`${prefix}: ${problem}`);
    }
    for (const problem of endpointMapProblems(snapshot, endpointMap)) {
      problems.push(`${prefix}: ${problem}`);
    }
    const item = catalog.find((entry) => entry?.type === identity.type);
    if (isObject(item) && isObject(snapshot)) {
      if (
        typeof snapshot.leaderboardId === "string" &&
        snapshot.leaderboardId !== item.leaderboardId
      ) {
        problems.push(
          `${prefix}: leaderboardId does not match scripts/frontier/catalog.json`
        );
      }
      if (
        typeof snapshot.sourceUrl === "string" &&
        snapshot.sourceUrl !== item.sourceUrl
      ) {
        problems.push(
          `${prefix}: sourceUrl does not match scripts/frontier/catalog.json`
        );
      }
    }
    if (!isObject(snapshot)) continue;
    if ((snapshot.derived === true) !== identity.derived) {
      problems.push(
        identity.derived
          ? `${prefix}: the snapshot must be derived: true`
          : `${prefix}: only a derived type may set derived: true`
      );
      continue;
    }
    if (identity.derived && Array.isArray(snapshot.sources)) {
      for (const problem of derivedSourceProblems(
        snapshot,
        endpointMap,
        catalog,
        repoRoot
      )) {
        problems.push(`${prefix}: ${problem}`);
      }
    }
  }
  return problems;
}

/**
 * Resolve a derived snapshot's sources through the catalog and check the
 * derivation. The snapshot links its first source.
 */
function derivedSourceProblems(snapshot, endpointMap, catalog, repoRoot) {
  const problems = [];
  const sources = [];
  for (const leaderboardId of snapshot.sources) {
    const item = catalog.find(
      (entry) =>
        isObject(entry) &&
        entry.derived === false &&
        entry.leaderboardId === leaderboardId
    );
    if (item === undefined) {
      problems.push(
        `source ${JSON.stringify(leaderboardId)} is not a leaderboard in scripts/frontier/catalog.json`
      );
      continue;
    }
    const sourcePath = path.join(
      repoRoot,
      "scripts",
      "frontier",
      item.type,
      "leaderboard.json"
    );
    if (!fs.existsSync(sourcePath)) {
      problems.push(
        `source ${JSON.stringify(leaderboardId)} has no snapshot in scripts/frontier/${item.type}`
      );
      continue;
    }
    sources.push({ item, snapshot: readJson(sourcePath) });
  }
  if (problems.length > 0) return problems;
  if (snapshot.sourceUrl !== sources[0].item.sourceUrl) {
    problems.push(
      `sourceUrl must be the ${sources[0].item.type} sourceUrl, its first source`
    );
  }
  problems.push(
    ...derivedProblems(
      snapshot,
      endpointMap,
      sources.map((source) => ({
        leaderboardId: source.item.leaderboardId,
        entries: source.snapshot?.entries,
      }))
    )
  );
  return problems;
}

function loadPresent(repoRoot) {
  const present = new Map();
  for (const identity of TYPE_IDENTITY) {
    const dir = path.join(repoRoot, "scripts", "frontier", identity.type);
    if (!fs.existsSync(dir)) continue;
    present.set(identity.type, {
      snapshot: readJson(path.join(dir, "leaderboard.json")),
      endpointMap: readJson(path.join(dir, "endpoints.json")),
    });
  }
  return present;
}

/**
 * The six types, with entries filled only where a directory exists.
 *
 * `sources` lists, for a derived type, the leaderboards it re-ranks. The docs
 * link them; the registry does not carry them.
 *
 * @returns {{
 *   types: object[],
 *   frontier: Record<string, { entries: object[] }>,
 *   sources: Record<string, Array<{ leaderboardId: string, sourceUrl: string }>>,
 * }}
 */
export function loadFrontierModel(repoRoot = REPO_ROOT) {
  const catalog = loadCatalog(
    path.join(repoRoot, "scripts", "frontier", "catalog.json")
  );
  const present = loadPresent(repoRoot);
  const types = [];
  const frontier = {};
  const sources = {};
  for (const identity of TYPE_IDENTITY) {
    const item = catalog.find((entry) => entry.type === identity.type);
    const loaded = present.get(identity.type);
    const capturedOn = loaded?.snapshot.capturedOn ?? "";
    const methodology = loaded?.snapshot.methodology ?? "";
    const leaderboardId = item.leaderboardId;
    const sourceUrl = item.sourceUrl;
    types.push({
      type: identity.type,
      name: identity.name,
      aliases: identity.aliases,
      leaderboardId,
      sourceUrl,
      capturedOn,
      methodology,
      derived: identity.derived,
    });
    const entries = loaded
      ? loaded.snapshot.entries.map((entry) => ({
          rank: entry.rank,
          model: entry.model,
          creator: entry.creator,
          elo: entry.elo,
          endpoints: loaded.endpointMap[entry.model] ?? [],
        }))
      : [];
    frontier[identity.type] = {
      leaderboardId,
      sourceUrl,
      capturedOn,
      methodology,
      entries,
    };
    if (identity.derived && Array.isArray(loaded?.snapshot.sources)) {
      sources[identity.type] = loaded.snapshot.sources.map((id) => ({
        leaderboardId: id,
        sourceUrl:
          catalog.find((entry) => entry.leaderboardId === id)?.sourceUrl ?? "",
      }));
    }
  }
  return { types, frontier, sources };
}

export async function renderFrontierModule(repoRoot = REPO_ROOT) {
  const problems = structuralProblems(repoRoot);
  if (problems.length > 0) {
    throw new Error(problems.join("\n"));
  }
  const { types, frontier } = loadFrontierModel(repoRoot);
  const source = `${DATA_HEADER}

export const FRONTIER_TYPES = ${JSON.stringify(types, null, 2)};

export const FRONTIER = ${JSON.stringify(frontier, null, 2)};
`;
  const config = (await prettier.resolveConfig(FRONTIER_DATA_PATH)) ?? {};
  return prettier.format(source, {
    ...config,
    filepath: FRONTIER_DATA_PATH,
  });
}

/**
 * First README group heading for a dot path, matching doc-gen's sectionKey
 * after HTTP verbs are removed. The anchor is that heading lowercased.
 */
export function readmeGroup(dotPath) {
  const segments = dotPath.split(".").filter((segment) => !VERBS.has(segment));
  for (const segment of segments) {
    if (/^v\d+$/i.test(segment)) continue;
    if (segment === "api") continue;
    return segment;
  }
  return "general";
}

function endpointHref(provider, dotPath, readmes) {
  const group = readmeGroup(dotPath);
  const readme = readmes.get(provider) ?? "";
  const base = `../packages/provider/${provider}/README.md`;
  if (
    readme.includes(`\n### ${group}\n`) ||
    readme.startsWith(`### ${group}\n`)
  ) {
    return `${base}#${group.toLowerCase()}`;
  }
  return base;
}

function endpointLink(entry, readmes) {
  const label = entry.modelId ?? entry.dotPath;
  const href = endpointHref(entry.provider, entry.dotPath, readmes);
  return `[${entry.provider} \`${label}\`](${href})`;
}

export function formatEndpoints(endpoints, readmes = new Map()) {
  if (!Array.isArray(endpoints) || endpoints.length === 0) {
    return UNMAPPED_LABEL;
  }
  return endpoints.map((entry) => endpointLink(entry, readmes)).join(", ");
}

function providerReadmes(providers, repoRoot) {
  const readmes = new Map();
  for (const provider of providers) {
    const readmePath = path.join(
      repoRoot,
      "packages",
      "provider",
      provider,
      "README.md"
    );
    readmes.set(
      provider,
      fs.existsSync(readmePath) ? fs.readFileSync(readmePath, "utf8") : ""
    );
  }
  return readmes;
}

let priceCatalog;

/**
 * Prices for the current endpoints.json files, keyed by type, model, index.
 *
 * One tsx process. The renderer and `frontier()` share frontierPrice.
 */
function loadFrontierPrices() {
  if (priceCatalog !== undefined) return priceCatalog;
  const script = path.join(HERE, "frontier-price-catalog.ts");
  const result = spawnSync(process.execPath, ["--import", "tsx", script], {
    cwd: REPO_ROOT,
    encoding: "utf8",
  });
  if (result.status !== 0) {
    const detail = result.stderr || result.stdout || "no output";
    throw new Error(`frontier price catalog failed:\n${detail}`);
  }
  priceCatalog = JSON.parse(result.stdout);
  return priceCatalog;
}

function joinList(items) {
  if (items.length <= 1) return items[0] ?? "";
  if (items.length === 2) return `${items[0]} and ${items[1]}`;
  return `${items.slice(0, -1).join(", ")} and ${items[items.length - 1]}`;
}

/**
 * Mention rate dates when they are not exactly the leaderboard capture date.
 * Dynamic and unpriced rows have no date.
 */
function priceAsOfSentence(dates, capturedOn) {
  const unique = [...new Set(dates)].sort();
  if (unique.length === 0) return "";
  if (unique.length === 1 && unique[0] === capturedOn) return "";
  return ` Prices as of ${joinList(unique)}.`;
}

function pricedCells(type, entry, catalog) {
  const texts = [];
  const dates = [];
  entry.endpoints.forEach((endpoint, index) => {
    const key = `${type}\t${entry.model}\t${index}`;
    const hit = catalog[key];
    if (hit === undefined) {
      throw new Error(`frontier price catalog is missing ${key}`);
    }
    texts.push(hit.text);
    if (hit.price !== null && typeof hit.price.asOf === "string") {
      dates.push(hit.price.asOf);
    }
  });
  return { text: texts.length === 0 ? "-" : texts.join(", "), dates };
}

function typeSection(info, snapshot, sources, readmes, catalog) {
  const heading = `## ${info.name} (\`${info.type}\`)`;
  if (snapshot.entries.length === 0) {
    const intro = info.derived
      ? "Derived. Artificial Analysis publishes no reference-to-video leaderboard."
      : `[${info.leaderboardId}](${info.sourceUrl})`;
    return `${heading}\n\n${intro}\n\n${NO_DATA_LABEL}\n`;
  }
  // A derived list links every board it re-ranks; its methodology says how.
  const boards = info.derived
    ? sources
        .map((source) => `[${source.leaderboardId}](${source.sourceUrl})`)
        .join(" and ")
    : `[${info.leaderboardId}](${info.sourceUrl})`;
  const dates = [];
  const rows = snapshot.entries.map((entry) => {
    const price = pricedCells(info.type, entry, catalog);
    dates.push(...price.dates);
    return { entry, price: price.text };
  });
  const prose = wrapProse(
    `${boards}, captured ${info.capturedOn}. ${info.methodology}${priceAsOfSentence(dates, info.capturedOn)}`
  );
  const lines = [
    heading,
    "",
    prose,
    "",
    "| Rank | Model | Creator | Elo | Price | apicity endpoints |",
    "| ---- | ----- | ------- | --- | ----- | ----------------- |",
  ];
  for (const row of rows) {
    lines.push(
      `| ${row.entry.rank} | ${row.entry.model} | ${row.entry.creator} | ${row.entry.elo} | ${row.price} | ${formatEndpoints(row.entry.endpoints, readmes)} |`
    );
  }
  return `${lines.join("\n")}\n`;
}

export async function renderFrontierDocument(repoRoot = REPO_ROOT) {
  const problems = structuralProblems(repoRoot);
  if (problems.length > 0) {
    throw new Error(problems.join("\n"));
  }
  const { types, frontier, sources } = loadFrontierModel(repoRoot);
  const providers = new Set();
  for (const snapshot of Object.values(frontier)) {
    for (const entry of snapshot.entries) {
      for (const endpoint of entry.endpoints) {
        if (typeof endpoint.provider === "string") {
          providers.add(endpoint.provider);
        }
      }
    }
  }
  const readmes = providerReadmes(providers, repoRoot);
  const catalog = loadFrontierPrices();
  const sections = types.map((info) =>
    typeSection(
      info,
      frontier[info.type],
      sources[info.type] ?? [],
      readmes,
      catalog
    )
  );
  const refresh = wrapProse(
    'Paste a new leaderboard into `scripts/frontier/<type>/leaderboard.json` and update `scripts/frontier/<type>/endpoints.json` so every model has an endpoint list or an explicit empty list. A dedicated leaf sets pricingKey to its PRICING key (for fal, the upstream endpoint id) or "unpriced". A shared callable prices by modelId. Keep ranks contiguous from 1 and stop at 10, or list every model when the board has fewer than 10. Bump the capture date, run `pnpm run gen:frontier` and `pnpm run doc-gen`, and commit the JSON with the regenerated registry and this file. A `t2v` or `i2v` refresh also re-derives `r2v`: list the models of both top 10 that have a reference-to-video endpoint, better Elo first, each with that Elo and that board\'s creator. The generator refuses a derived list that no longer matches its sources. Nothing in code, tests, or CI may download a leaderboard or a price.'
  );
  const source = [
    "# Frontier models",
    "",
    wrapProse(COVERAGE_SENTENCE),
    "",
    ...sections,
    "## Refresh",
    "",
    refresh,
    "",
  ].join("\n");
  const config = (await prettier.resolveConfig(DOCS_PATH)) ?? {};
  return prettier.format(source, { ...config, filepath: DOCS_PATH });
}

/**
 * Write or compare docs/frontier.md.
 *
 * @returns {Promise<string | null>} `docs/frontier.md` when `--check` drifts
 */
export async function syncFrontierDoc({ check, repoRoot = REPO_ROOT }) {
  const docPath = path.join(repoRoot, "docs", "frontier.md");
  const next = await renderFrontierDocument(repoRoot);
  const current = fs.existsSync(docPath)
    ? fs.readFileSync(docPath, "utf8")
    : "";
  if (next === current) return null;
  if (check) return "docs/frontier.md";
  fs.mkdirSync(path.dirname(docPath), { recursive: true });
  fs.writeFileSync(docPath, next);
  return null;
}

